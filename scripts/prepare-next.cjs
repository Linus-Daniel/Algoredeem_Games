const fs=require('node:fs/promises');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const {ROOT,PUBLIC_FILES}=require('./serve.cjs');
async function prepare(){
 if(process.argv.includes('--production'))process.env.NODE_ENV='production';
 require('./create-player.cjs').createPlayer();
 const result=spawnSync(process.execPath,['scripts/build.cjs'],{cwd:ROOT,stdio:'inherit'});if(result.status!==0)throw new Error('Offline build failed');
 const dir=path.join(ROOT,'public');await fs.rm(dir,{recursive:true,force:true});await fs.mkdir(dir,{recursive:true});
 const files=[...PUBLIC_FILES].filter(file=>!['index.html','sw.js'].includes(file));files.push('assets/player.js','assets/ads-consent.js');
 for(const file of files){await fs.mkdir(path.dirname(path.join(dir,file)),{recursive:true});await fs.copyFile(path.join(['assets/player.js','assets/ads-consent.js'].includes(file)?ROOT:path.join(ROOT,'dist'),file),path.join(dir,file));}
 const gumdrop=await fs.readFile(path.join(dir,'gumdrop.html'),'utf8');await fs.writeFile(path.join(dir,'gumdrop.html'),gumdrop.replace('href="index.html"','href="/" target="_top"'));
 await fs.writeFile(path.join(dir,'sw.js'),"/* Next.js development preview: offline caching is generated by the production export. */\n");
 console.log('Prepared Next.js assets and isolated game player.');
}
prepare().catch(e=>{console.error(e);process.exitCode=1;});
